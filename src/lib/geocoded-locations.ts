const ONLINE_KEYWORDS = ["online", "virtual", "remote", "nationwide", "national", "international", "anywhere"];

export function isOnlineLocation(location: string | null): boolean {
  const value = (location ?? "").trim().toLowerCase();
  if (!value) return true;
  return ONLINE_KEYWORDS.some((kw) => value.includes(kw));
}

