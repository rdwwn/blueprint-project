export function geocodeLocation(location: string | null): Coordinates {
  const value = (location ?? "").trim();
  if (!value) return GEOCODED_LOCATIONS.Nationwide;
  if (isOnlineLocation(value)) return GEOCODED_LOCATIONS.Nationwide;
  if (GEOCODED_LOCATIONS[value]) return GEOCODED_LOCATIONS[value];
  const lower = value.toLowerCase();
  // Prefer a city name before a state-level match so "Stanford, CA" hits
  // the campus instead of the state center.
  const city = Object.keys(GEOCODED_LOCATIONS).find((key) => key.length > 4 && lower.includes(key.toLowerCase()));
  if (city) return GEOCODED_LOCATIONS[city];
  const exactState = Object.keys(STATE_ALIASES).find((state) => lower.includes(state));
  if (exactState) return GEOCODED_LOCATIONS[STATE_ALIASES[exactState]];
  // Fall back to state abbreviations, matched on word boundaries so
  // "Carnegie Mellon" doesn't hit "CA" or "New" doesn't hit "NV".
  const abbrev = STATE_ABBREV_PATTERNS.find(({ pattern }) => pattern.test(lower));
  if (abbrev) return GEOCODED_LOCATIONS[abbrev.state];
  return GEOCODED_LOCATIONS.Nationwide;
}
